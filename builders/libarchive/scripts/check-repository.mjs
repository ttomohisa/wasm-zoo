import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
const root=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'..');
const errors=[]; const read=(p)=>fs.readFileSync(path.join(root,p),'utf8'); const need=(ok,msg)=>{if(!ok)errors.push(msg)};
const env=read('versions.env');
need(env.includes('BUILDER_VERSION=0.3.0'),'builder version must be 0.3.0');
need(env.includes('LIBARCHIVE_REF=v3.8.9'),'libarchive must pin v3.8.9');
need(env.includes('LIBARCHIVE_COMMIT=27cbc7827172698143e440801fc0ba39ccb4f1f5'),'libarchive exact commit pin is missing');
const build=read('scripts/build-full.sh');
const profile=read('profiles/browser-full/profile.env');
need(profile.includes('PROFILE_DISPLAY_NAME=\"Browser Full\"'),'profile display name with spaces must be shell-quoted');
need(!profile.includes('PROFILE_DISPLAY_NAME=Browser Full'),'profile display name must not be an unquoted shell assignment');
for(const tool of ['bsdtar','bsdcpio','bsdcat','bsdunzip']) need(build.includes(tool),`build must include ${tool}`);
for(const flag of ['-DENABLE_ZLIB=ON','-DENABLE_BZip2=ON','-DENABLE_TEST=OFF','-DBUILD_SHARED_LIBS=OFF','-DENABLE_LIBGCC=OFF','-DENABLE_WIN32_XMLLITE=OFF','-DPOSIX_REGEX_LIB=LIBC','-sMODULARIZE=1','-sFORCE_FILESYSTEM=1']) need(build.includes(flag),`build flag missing: ${flag}`);
need(!build.includes('-pthread'),'libarchive browser-full should remain single-threaded');
for(const file of ['LICENSES/zlib-LICENSE.txt','LICENSES/bzip2-LICENSE.txt']) need(fs.existsSync(path.join(root,file)),`third-party notice missing: ${file}`);
need(build.includes('zlib 1.3.2') && build.includes('bzip2 1.0.6'),'pinned Emscripten port versions must be recorded in build output');
const runtime=read('runtime/browser-libarchive.js');
need(runtime.includes('createLibarchiveCore'),'runtime must load the modularized upstream CLI core');
need(runtime.includes('collectDirs'),'runtime must support directory extraction results');
const smoke=read('tests/smoke-test.html');
need(smoke.includes("['-tf', '/fixture.zip']"),'smoke test must list a real ZIP');
need(smoke.includes("['-xf', '/fixture.zip', '-C', '/out']"),'smoke test must extract a real ZIP');
if(errors.length){console.error(`[NG] ${errors.length} libarchive builder check(s)`);for(const e of errors)console.error(` - ${e}`);process.exit(1);}console.log('[OK] libarchive browser-full repository checks passed');
